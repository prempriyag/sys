# Normalized key for lookup: (state_lower, district_lower) -> list of AC names
_AC_LOOKUP = {((s.lower(), d.lower())): acs for (s, d), acs in STATE_DISTRICT_AC.items()}


def get_assembly_constituencies(state_name: str, district_name: str) -> list[str]:
    """Return list of Assembly Constituency names for the given state and district, or empty list."""
    s = (state_name or "").strip().lower()
    d = (district_name or "").strip().lower()
    return list(_AC_LOOKUP.get((s, d), []))
